#!/usr/bin/env python3
"""Emit portable, byte-defined MS OS 1.0 descriptors for the ADB interface."""
import argparse
from pathlib import Path
import struct

HERE = Path(__file__).resolve().parent
GUID = '{F72FE0D4-CBCB-407D-8814-9ED673D0DD6B}'
VENDOR_REQUEST = 0xDA

def descriptors():
    string = bytes((18, 3)) + 'MSFT100'.encode('utf-16le') + bytes((VENDOR_REQUEST, 0))
    compatible = (struct.pack('<IHHB7x', 40, 0x100, 4, 1)
                  + bytes((0, 1)) + b'WINUSB\0\0' + bytes(14))
    name = ('DeviceInterfaceGUIDs\0').encode('utf-16le')
    value = (GUID + '\0\0').encode('utf-16le')
    section = struct.pack('<IIH', 14 + len(name) + len(value), 7, len(name)) + name + struct.pack('<I', len(value)) + value
    properties = struct.pack('<IHHH', 10 + len(section), 0x100, 5, 1) + section
    return {'daos_ms_os_string': string, 'daos_ms_compatible_id': compatible,
            'daos_ms_extended_properties': properties}

def content():
    lines = ['/* SPDX-License-Identifier: BSD-2-Clause */',
             '/* Generated by generate_descriptors.py; lengths are USB wire bytes. */',
             '#ifndef DAOS_ADB_MS_OS_H', '#define DAOS_ADB_MS_OS_H',
             '#ifdef _KERNEL', '#include <sys/stdint.h>', '#else', '#include <stdint.h>', '#endif',
             '#define DAOS_ADB_VENDOR_REQUEST 0xDA', '']
    for name, blob in descriptors().items():
        lines.append('static const uint8_t %s[%d] = {' % (name, len(blob)))
        for offset in range(0, len(blob), 12):
            lines.append('    ' + ', '.join('0x%02x' % b for b in blob[offset:offset+12]) + ',')
        lines.extend(('};', ''))
    lines.extend(['static inline const uint8_t *',
                  'daos_ms_vendor_descriptor(uint8_t type, uint8_t request, uint16_t index, uint16_t value, uint16_t *length)',
                  '{', '    *length = 0;',
                  '    if (request != DAOS_ADB_VENDOR_REQUEST || value != 0) return (const uint8_t *)0;',
                  '    if (type == 0xc0 && index == 4) {',
                  '        *length = sizeof(daos_ms_compatible_id); return daos_ms_compatible_id;',
                  '    }',
                  '    if ((type == 0xc1 || type == 0xc0) && index == 5) {',
                  '        *length = sizeof(daos_ms_extended_properties); return daos_ms_extended_properties;',
                  '    }', '    return (const uint8_t *)0;', '}', '#endif', ''])
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); target = HERE / 'daos_ms_os.h'
    if args.check:
        if target.read_text() != content(): raise SystemExit('Descriptor header is stale')
    else: target.write_text(content(), encoding='utf-8', newline='\n')
